--   724,800행 · 255 MB · 28일치 · 자체 정리 크론 없음
-- DB 전체가 1,404 MB이므로 **18%가 순수 로그**다. pg_cron은 이 테이블을 스스로 지우지 않는다.
-- 게다가 이건 우리 데이터가 아니라 운영 부산물이라, 요금제 용량 한도를 이걸로 먹는 건 손해다.
