-- 7일치만 남긴다 - 실패한 작업을 사후 확인하기엔 충분하고(실패는 28일간 147건뿐),
-- 그보다 오래된 성공 기록은 아무도 보지 않는다.
--
-- 되돌리기: select cron.unschedule('cleanup_cron_job_run_details');
select cron.schedule(
  'cleanup_cron_job_run_details',
  '17 4 * * *',   -- 매일 04:17 UTC(한국 13:17). 매분 도는 다른 작업과 겹치지 않게 분을 어긋냄
  $$delete from cron.job_run_details where start_time < now() - interval '7 days'$$
);

